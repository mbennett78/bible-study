const ENDINGS = [["ies", "y"], ["'s", ""], ["’s", ""], ["eth", ""], ["est", ""], ["ing", ""], ["ed", ""], ["es", ""], ["s", ""]];
// The plain meaning for a word, trying simple forms ("sins" -> "sin", "baptized" -> "baptize").
export function glossFor(word) {
  const w = word.toLowerCase();
  if (GLOSSARY[w]) return { term: w, text: GLOSSARY[w] };
  for (const [end, add] of ENDINGS) {
    if (!w.endsWith(end) || w.length - end.length < 3) continue;
    const base = w.slice(0, -end.length) + add;
    for (const f of [base, `${base}e`]) if (GLOSSARY[f]) return { term: f, text: GLOSSARY[f] };
  }
  return null;
}
export function stem(word) {
  let w = word.toLowerCase().replace(/[’']s$/, "");
  for (const [end] of ENDINGS.slice(3)) if (w.endsWith(end) && w.length - end.length >= 3) { w = w.slice(0, -end.length); break; }
  return w;
}
